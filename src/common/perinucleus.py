"""Perinucleus fingerprint records (Nasery et al., 2025), standard library only.

Everything training and direct verification consume is stored as token ids
(Llama-3.1 tokenizer); text fields are decodes kept for the workflow prompts.
Dataset: data/fingerprints/perinucleus/ (1,024 trained + 128 never-trained keys).
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parents[2]
DATASET_DIR = ROOT / "data" / "fingerprints" / "perinucleus"
UPSTREAM_REPO = "https://github.com/SewoongLab/scalable-fingerprinting-of-llms"
UPSTREAM_COMMIT = "fdceaba14bd3e89340916a6a40e27c945d48460e"

# Stage generated by the fingerprinted model whose first token decides the run outcome.
PRIMARY_STAGE = {"react": "model_output_raw", "tool_use": "model_output_raw", "multi_agent": "executor_output"}


@dataclass(frozen=True)
class PerinucleusPair:
    pair_id: int
    split: str                 # 'train' (1,024 fingerprints) | 'heldout' (128 never-trained keys)
    key_ids: Tuple[int, ...]   # 16 key token ids, no BOS
    key_text: str
    target_id: int
    target_text: str

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "PerinucleusPair":
        return cls(int(d["pair_id"]), str(d["split"]), tuple(int(x) for x in d["key_ids"]), str(d["key_text"]),
                   int(d["target_id"]), str(d["target_text"]))


@dataclass(frozen=True)
class BenignExample:
    """Data-mixing example: a natural 16-token prefix and its true next token."""

    example_id: int
    key_ids: Tuple[int, ...]
    target_id: int
    source_index: int

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "BenignExample":
        return cls(int(d["example_id"]), tuple(int(x) for x in d["key_ids"]), int(d["target_id"]),
                   int(d.get("source_index", -1)))


def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    with Path(path).open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def write_jsonl(path: Path, rows: Iterable[Dict[str, Any]]) -> int:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
    return n


def read_pairs(path: Path = DATASET_DIR / "pairs.jsonl", split: Optional[str] = None) -> List[PerinucleusPair]:
    pairs = [PerinucleusPair.from_dict(r) for r in read_jsonl(path)]
    return [p for p in pairs if split is None or p.split == split]


def read_benign(path: Path = DATASET_DIR / "benign_pool.jsonl") -> List[BenignExample]:
    return [BenignExample.from_dict(r) for r in read_jsonl(path)]


def canonical_json(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def dataset_hash(pairs: Iterable[PerinucleusPair]) -> str:
    """Content hash over ids and split only (38209ca9... for the released dataset)."""
    core = [[p.pair_id, p.split, list(p.key_ids), p.target_id] for p in sorted(pairs, key=lambda x: x.pair_id)]
    return sha256_text(canonical_json(core))


def key_ids_contiguous(sequence: Sequence[int], key_ids: Sequence[int]) -> bool:
    """Whether the trained key ids occur contiguously in a tokenised prompt.

    False marks an interface effect (e.g. a preceding space merged with the
    first key token), reported separately from fingerprint failure.
    """
    k = list(key_ids)
    if not k or len(k) > len(sequence):
        return False
    return any(list(sequence[i:i + len(k)]) == k for i in range(len(sequence) - len(k) + 1))


def run_outcome(architecture: str, stages: Iterable[Any], target_id: int) -> Optional[str]:
    """'fired' / 'not_fired' from the first token of the primary stage."""
    wanted = PRIMARY_STAGE[architecture]
    for stage in stages:
        if stage.stage_id == wanted:
            first = stage.metadata.get("first_token_id")
            if first is None:
                return None
            return "fired" if int(first) == int(target_id) else "not_fired"
    return None
